// 诊断码到用户可见摘要的固定映射；与 `DESIGNER_UI_TEXT.diagnostics` 同源。
export function designerDiagnosticSummary(code: ScreenDiagnostic['code']): string {
  switch (code) {
    case 'PROJECT_CONFLICT':
      return DESIGNER_UI_TEXT.diagnostics.projectConflict;
    case 'PROJECT_UNAVAILABLE':
      return DESIGNER_UI_TEXT.diagnostics.projectUnavailable;
    case 'PROJECT_ABORTED':
      return DESIGNER_UI_TEXT.diagnostics.projectAborted;
    case 'PROJECT_DIRTY':
      return DESIGNER_UI_TEXT.diagnostics.projectDirty;
    case 'PROJECT_PUBLISH_UNAVAILABLE':
      return DESIGNER_UI_TEXT.diagnostics.projectPublishUnavailable;
    case 'BLUEPRINT_CAPABILITY_UNAVAILABLE':
      return DESIGNER_UI_TEXT.diagnostics.blueprintCapabilityUnavailable;
    case 'HOST_RESOURCE_TIMEOUT':
    case 'HOST_RESOURCE_FAILED':
    case 'HOST_RESOURCE_INVALID':
      return DESIGNER_UI_TEXT.diagnostics.hostResourceUnavailable;
    case 'CORE_COMMAND_TARGET_LOCKED':
      return DESIGNER_UI_TEXT.diagnostics.commandTargetLocked;
    case 'CORE_COMMAND_TARGET_HIDDEN':
      return DESIGNER_UI_TEXT.diagnostics.commandTargetHidden;
    case 'PLUGIN_CORE_LIFECYCLE_INVALID':
      return DESIGNER_UI_TEXT.diagnostics.lifecycleInvalid;
    default:
      return DESIGNER_UI_TEXT.diagnostics.genericFailure;
  }
}
